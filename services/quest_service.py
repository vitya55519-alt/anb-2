PATH_STEP = 8.0  # axis movement per canonical quest answer


def path_points(inclination: str | None) -> int:
    """V3.59.3: signed axis change a choice gives (+passion / -tenderness),
    shown next to the button so the player sees what the choice does."""
    if inclination == 'bold':
        return int(PATH_STEP)
    if inclination == 'romance':
        return -int(PATH_STEP)
    return 0


def route_points(quest_key: str, route_key: str) -> int:
    return path_points(ROUTE_INCLINATION.get((quest_key, route_key)))


def _apply_path(session, uid: int, character_id: str, inclination: str) -> None:
    """V3.50.0: nudge the per-character path axis. Romance -> negative,
    bold -> positive, clamped to [-100, 100]. No-op for neutral or when the
    relationship row does not exist yet."""
    if inclination not in ('romance', 'bold'):
        return
    row = session.scalar(select(UserCharacterRelationship).where(
        UserCharacterRelationship.user_id == uid,
        UserCharacterRelationship.character_id == character_id,
    ))
    if row is None:
        # V3.51.1: playing a story for a character you never chatted with must
        # still open *her* path — create the relationship row (all scores are
        # neutral by default) so the axis persists and the card scale appears.
        row = UserCharacterRelationship(user_id=uid, character_id=character_id, path_axis=0.0)
        session.add(row)
        session.flush()
    delta = -PATH_STEP if inclination == 'romance' else PATH_STEP
    row.path_axis = max(-100.0, min(100.0, (getattr(row, 'path_axis', 0.0) or 0.0) + delta))


